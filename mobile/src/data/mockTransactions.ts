export function findNextPendingTier3(currentId?: string): Transaction | undefined {
  const tier3 = pendingTransactions.filter((t) => t.tier === 3 && t.status === 'pending');
  if (!currentId) return tier3[0];
  const i = tier3.findIndex((t) => t.id === currentId);
  if (i < 0) return tier3[0];
  return tier3[i + 1];
}
